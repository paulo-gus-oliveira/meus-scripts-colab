import asyncio
import numpy as np
import pandas as pd
from playwright.async_api import async_playwright
from bs4 import BeautifulSoup
import nest_asyncio
import yfinance as yf

nest_asyncio.apply()  # Apply the patch to allow nested event loops

async def fundamentus_dataframe(papeis):
    """
    Extracts fundamentus data for a list of paper codes and returns a combined DataFrame.

    Args:
        papeis (list): A list of paper codes (e.g., ["klbn4", "petr4"]).

    Returns:
        pd.DataFrame: A combined DataFrame containing fundamentus data for the provided papers,
                      or an empty DataFrame if no data was extracted.
    """

    all_dfs = []

    async with async_playwright() as p:
        browser = await p.chromium.launch(headless=True)

        for papel in papeis:
            url = f"https://fundamentus.com.br/proventos.php?papel={papel}"
            page = await browser.new_page()

            try:
                await page.goto(url, timeout=60000)
                await page.wait_for_selector("#resultado", timeout=60000)
                html = await page.content()

                soup = BeautifulSoup(html, "html.parser")
                table = soup.find("table", {"id": "resultado"})

                if table:
                    header = [th.text.strip() for th in table.find("thead").find_all("th")]
                    data = []
                    for row in table.find("tbody").find_all("tr"):
                        cols = row.find_all("td")
                        data.append([col.text.strip() for col in cols])

                    df = pd.DataFrame(data, columns=header)
                    df['Papel'] = papel
                    all_dfs.append(df)
                    print(f"Dados de {papel} extraídos.")
                else:
                    print(f"Tabela #resultado não encontrada para {papel}")

            except Exception as e:
                print(f"Erro ao processar {papel}: {e}")
            finally:
                await page.close()  # Ensure the page is closed in all cases

        await browser.close()

    if all_dfs:
        final_df = pd.concat(all_dfs, ignore_index=True)
        #print("\nDataFrame Combinado:\n")
        #print(final_df)
        return final_df
    else:
        print("Nenhum dado foi extraído.")
        return pd.DataFrame()

