from bcb import sgs
import pandas as pd
import numpy as np
import plotly_express as px
import yfinance as yf
import statsmodels.api as sm

# Define the date range
start_date = '2025-01-01'
end_date = '2025-12-31'

#Baixando os dados dos ativos
tickers = ['mglu3.sa','sanb3.sa','bbdc3.sa','bbdc4.sa','b3sa3.sa','sapr4.sa','klbn4.sa','itub3.sa','itub4.sa','itsa4.sa','ggbr4.sa','vale3.sa','brap3.sa',
           'bbas3.sa', 'petr4.sa','petr3.sa','taee3.sa','taee4.sa','bbse3.sa','cxse3.sa','alup3.sa','cple3.sa','^BVSP']

def data_set_ativos(tickers, start_date, end_date):

    data = yf.download(tickers, start=start_date, end=end_date)['Close']

    # Organizando os dados em um DataFrame
    df = data.reset_index().melt(id_vars='Date', var_name='Ativo', value_name='Fechamento')


    df = df.astype({'Ativo': 'category', 'Fechamento': 'float64'})
    df = df.assign(Date=pd.to_datetime(df["Date"], errors="coerce"))


    # Pivot the DataFrame to have stocks as columns
    wide_df = df.pivot(index='Date', columns='Ativo', values='Fechamento')

    # Reset index to make 'Date' a column again (optional)
    wide_df = wide_df.reset_index().set_index('Date')
    #wide_df = wide_df

    # Display the result
    return wide_df

wide_df = data_set_ativos(tickers, start_date, end_date)
wide_df.head(3)

# # Define the date range


# Buscar série 11 (SELIC diária)
selic_day = sgs.get({'selic': 11}, start=start_date, end=end_date)
selic_day = selic_day/100

selic_day = selic_day.astype({'selic': 'float64'})

#selic_day = selic_day.assign(Date=pd.to_datetime(selic_day["Date"], errors="coerce"))


# A série já vem como DataFrame do pandas
#print(selic_day.head())
selic_diaria = selic_day[1:]
selic_diaria.head()

dataset = wide_df.copy()

# Remove columns that are entirely NaN (e.g., failed downloads)
dataset = dataset.dropna(axis=1, how='all')

# 1. Calcular retornos-simples
# Specify fill_method=None to suppress future warning
retornos = dataset.pct_change(fill_method=None)

# Merge with selic_diaria. This will automatically align by Date index.
# Rows with no matching index in either DataFrame will be dropped by default (inner join behavior).
retornos = pd.merge(retornos, selic_diaria, left_index=True, right_index=True, how='inner')

# Define benchmark
benchmark = '^BVSP'

# Drop any remaining rows with NaN values in critical columns for CAPM calculation
# Specifically, we need benchmark and Rf_diario (selic) to be non-NaN.
required_cols = [benchmark, 'selic']
retornos = retornos.dropna(subset=required_cols)

# Check if retornos is empty after initial cleaning
if retornos.empty:
    raise ValueError("DataFrame 'retornos' is empty after calculating returns and cleaning. Cannot proceed with CAPM.")

# 2. Definir taxa livre de risco (diária)
Rf_diario = retornos['selic']  # Selic diária

# 3. Calcular Beta para cada ativo
# Ensure that benchmark is in the columns after cleaning
if benchmark not in retornos.columns:
    raise ValueError(f"Benchmark '{benchmark}' not found in returns data after cleaning.")

ativos_total = [item.upper() for item in tickers]
# Filter out benchmark and any tickers that might have been dropped due to all NaNs in `dataset`
ativos_para_capm = [t for t in ativos_total if t != benchmark and t in retornos.columns]
ativos = ativos_para_capm

capm_results = {}
for ativo in ativos:
    # Get the premium for the market and the asset
    X_series = retornos[benchmark] - Rf_diario
    y_series = retornos[ativo] - Rf_diario

    # Combine X and y for this specific asset and drop NaNs for these two series
    # This ensures that OLS only uses valid data points for each asset.
    combined_data = pd.DataFrame({'X': X_series, 'y': y_series}).dropna()

    if combined_data.empty:
        print(f"Skipping CAPM for {ativo}: Not enough valid data points after aligning with benchmark and risk-free rate.")
        continue

    X = combined_data['X']
    y = combined_data['y']

    X = sm.add_constant(X)  # Add alpha (intercept)

    try:
        model = sm.OLS(y, X).fit()
        alpha, beta = model.params

        # Store results, ensure pvalues.iloc[1] exists for beta
        if len(model.pvalues) > 1:
            p_value_beta = model.pvalues.iloc[1]
        else:
            p_value_beta = np.nan # Or handle appropriately if OLS model is too simple

        capm_results[ativo] = {
            'Beta': beta,
            'Alpha': alpha,
            'R²': model.rsquared,
            'p-value Beta': p_value_beta,
        }
    except Exception as e:
        print(f"Error calculating CAPM for {ativo}: {e}")
        continue

# DataFrame de resultados
resultados_capm = pd.DataFrame(capm_results).T

if resultados_capm.empty:
    raise ValueError("No CAPM results were successfully calculated. 'resultados_capm' is empty.")


# 5. Calcular retorno esperado anualizado (CAPM)

# Ensure retornos[benchmark] and Rf_diario are not empty for these calculations
if retornos[benchmark].empty or Rf_diario.empty:
    E_Rm = 0
    Rf_anualizada = 0
else:
    E_Rm = (1 + retornos[benchmark]).prod() ** (252 / len(retornos)) - 1
    Rf_anualizada = (1 + Rf_diario).prod() ** (252 / len(Rf_diario)) - 1

E_Rm_minus_Rf = E_Rm - Rf_anualizada  # Prêmio de mercado anualizado

# This part needs to be careful if Beta is NaN due to empty capm_results
if not resultados_capm.empty and 'Beta' in resultados_capm.columns:
    resultados_capm['Retorno Esperado CAPM'] = (
        Rf_anualizada + resultados_capm['Beta'] * E_Rm_minus_Rf
    )
else:
    resultados_capm['Retorno Esperado CAPM'] = np.nan # Assign NaN if no betas

# Supondo que 'ativos' é a lista de tickers dos ativos (excluindo o benchmark)
# e que essas são as colunas em 'retornos' e índices em 'resultados_capm'
retornos_ativos_anualizados = {}
for ativo_ticker in resultados_capm.index: # ou use a lista 'ativos' definida anteriormente
    ret_ativo_anual = (1 + retornos[ativo_ticker]).prod() ** (252 / len(retornos[ativo_ticker])) - 1
    retornos_ativos_anualizados[ativo_ticker] = ret_ativo_anual

# Converta para uma Série alinhada com resultados_capm
retornos_ativos_anualizados_series = pd.Series(retornos_ativos_anualizados)

resultados_capm['Retorno Anualizado Ativo'] = retornos_ativos_anualizados_series
resultados_capm['Alfa_Jensen'] = resultados_capm['Retorno Anualizado Ativo'] - resultados_capm['Retorno Esperado CAPM']

#resultados_capm['alpha_linear'] = resultados_capm['Alpha'] * 252 # alpha aproximado
