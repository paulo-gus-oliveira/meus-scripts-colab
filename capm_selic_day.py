resultados_capm_sorted = resultados_capm.sort_values(by='Alfa_Jensen', ascending=False)
resultados_capm_sorted

df_capm = resultados_capm.copy()


if df_capm.empty or 'p-value Beta' not in df_capm.columns:
    if df_capm.empty and 'p-value Beta' not in capm_results: # Checa se a chave original também não existe
         print("A chave 'p-value Beta' não foi encontrada no dicionário original.")
    elif 'p-value Beta' not in df_capm.columns:
        print("A coluna 'p-value Beta' não foi encontrada no DataFrame.")
else:
    significance_level = 0.05
    all_significant = True
    non_significant_assets_df = []

    # Iterar sobre a coluna 'p-value Beta' do DataFrame
    # .items() em uma Series do Pandas retorna pares de (índice, valor)
    for asset_ticker, p_value in df_capm['p-value Beta'].items():
        if pd.isna(p_value): # Checa se o valor é NaN (Not a Number)
            print(f"Aviso: p-valor ausente (NaN) para o ativo {asset_ticker}. Ignorando.")
            continue # Pula para o próximo ativo

        if p_value > significance_level:
            all_significant = False
            non_significant_assets_df.append({'ativo': asset_ticker, 'p_value_beta': p_value})

    if all_significant:
        # Verifica se a lista non_significant_assets_df está realmente vazia,
        # pois um p-valor NaN pode ter feito com que não fosse adicionado,
        # mas não queremos dizer que "todos são significativos" se houve dados ausentes.
        # No entanto, a lógica atual já cuida disso, pois all_significant só se mantém True
        # se todos os p-valores válidos forem <= significance_level.
        print("todos são significativos.")
    else:
        print("\nUm ou mais Betas não são estatisticamente significativos (p-valor > 0.05):")
        for item in non_significant_assets_df:
            print(f"Ativo: {item['ativo']}, p-value Beta: {item['p_value_beta']}")



